#pragma once

#include <glib.h>

static const guint8 goodix_pr81_image[] = {
    0x81, 0x03, 0x27, 0x01, 0x21, 0x01, 0x27, 0x01, 0x23, 0x01
};
static const guint8 goodix_pr81_warmup[] = {
    0x01, 0x03, 0x27, 0x01, 0x21, 0x01, 0x27, 0x01, 0x23, 0x01
};
static const guint8 goodix_pr81_report[] = {
    0x0d, 0x01, 0x27, 0x01, 0x21, 0x01, 0x27, 0x01, 0x23, 0x01,
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x01
};

#define GOODIX_PR81_REGISTER 0x022c
#define GOODIX_PR81_START 0x030a
#define GOODIX_PR81_STOP 0x020a

static inline guint16 goodix_pr81_correct_pixel(guint16 value, guint16 offset)
{
    return CLAMP((gint32) value - (gint32) offset + 2048, 0, 4095);
}
