/* FDT reply: 4-byte header followed by eight little-endian region values. */
static inline gboolean goodix_pr81_read_regions(const guint8* data, gsize length,
                                                guint16 values[8])
{
    if (!data || length < 20)
        return FALSE;
    for (guint i = 0; i < 8; i++)
        values[i] = (guint16) data[4 + 2 * i] | ((guint16) data[5 + 2 * i] << 8);
    return TRUE;
}

static inline guint goodix_pr81_contact_regions(const guint16 baseline[8],
                                                const guint16 values[8])
{
    guint changed = 0;
    for (guint i = 0; i < 8; i++)
        changed += (gint32) baseline[i] - values[i] > 20;
    return changed;
}
